import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { format } from "prettier";

const PROJECT_ROOT = resolve(import.meta.dirname, "..");
const DEFAULT_INDEX_PATH = join(PROJECT_ROOT, "storybook-static/index.json");
const DEFAULT_JSON_PATH = join(PROJECT_ROOT, "docs/components/generated-inventory.json");
const DEFAULT_MARKDOWN_PATH = join(PROJECT_ROOT, "docs/components/INVENTORY.md");

function normalizeProjectPath(path) {
  return path.replaceAll("\\", "/").replace(/^\.\//, "");
}

function isRecord(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

export function createComponentInventory(storybookIndex) {
  if (!isRecord(storybookIndex?.entries)) {
    throw new Error("Storybook index must contain an entries object.");
  }

  const componentsByTitle = new Map();

  for (const entry of Object.values(storybookIndex.entries)) {
    if (!isRecord(entry) || entry.type !== "story") {
      continue;
    }

    const { componentPath, id, importPath, name, tags, title } = entry;
    if (
      typeof id !== "string" ||
      typeof importPath !== "string" ||
      typeof name !== "string" ||
      typeof title !== "string"
    ) {
      throw new Error("Each Storybook story must define id, name, title and importPath.");
    }

    const component = componentsByTitle.get(title) ?? {
      componentPath: typeof componentPath === "string" ? normalizeProjectPath(componentPath) : null,
      stories: [],
      storyPath: normalizeProjectPath(importPath),
      title,
    };

    component.stories.push({
      id,
      name,
      tags: Array.isArray(tags)
        ? tags
            .filter((tag) => typeof tag === "string")
            .sort((first, second) => first.localeCompare(second))
        : [],
    });
    componentsByTitle.set(title, component);
  }

  const components = [...componentsByTitle.values()]
    .map((component) => ({
      ...component,
      stories: component.stories.sort((first, second) => first.name.localeCompare(second.name)),
    }))
    .sort((first, second) => first.title.localeCompare(second.title));

  return {
    components,
    schemaVersion: 1,
    source: "storybook-static/index.json",
  };
}

function escapeTableCell(value) {
  return String(value).replaceAll("|", "\\|");
}

export function renderComponentInventoryMarkdown(inventory) {
  const lines = [
    "# Inventario Generado De Componentes",
    "",
    "<!-- Generated by scripts/generate-component-inventory.mjs. Do not edit manually. -->",
    "",
    `Fuente: \`${inventory.source}\`. Componentes: ${inventory.components.length}.`,
    "",
    "| Componente | Implementacion | Stories | Variantes |",
    "| --- | --- | --- | ---: |",
  ];

  for (const component of inventory.components) {
    lines.push(
      `| \`${escapeTableCell(component.title)}\` | \`${escapeTableCell(component.componentPath ?? "No declarada")}\` | \`${escapeTableCell(component.storyPath)}\` | ${component.stories.length} |`,
    );
  }

  for (const component of inventory.components) {
    lines.push("", `## ${component.title}`, "");
    for (const story of component.stories) {
      const tags =
        story.tags.length > 0 ? ` (${story.tags.map((tag) => `\`${tag}\``).join(", ")})` : "";
      lines.push(`- \`${story.id}\`: ${story.name}${tags}`);
    }
  }

  return `${lines.join("\n")}\n`;
}

async function assertCurrent(path, expectedContent) {
  let currentContent;
  try {
    currentContent = await readFile(path, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") {
      throw new Error(`Generated component inventory is missing: ${path}`, { cause: error });
    }
    throw error;
  }

  if (currentContent !== expectedContent) {
    throw new Error(
      `Generated component inventory is stale: ${path}. Run pnpm run components:inventory.`,
    );
  }
}

export async function generateComponentInventory({
  check = false,
  indexPath = DEFAULT_INDEX_PATH,
  jsonPath = DEFAULT_JSON_PATH,
  markdownPath = DEFAULT_MARKDOWN_PATH,
} = {}) {
  const storybookIndex = JSON.parse(await readFile(indexPath, "utf8"));
  const inventory = createComponentInventory(storybookIndex);
  const [json, markdown] = await Promise.all([
    format(JSON.stringify(inventory), { parser: "json" }),
    format(renderComponentInventoryMarkdown(inventory), { parser: "markdown" }),
  ]);

  if (check) {
    await Promise.all([assertCurrent(jsonPath, json), assertCurrent(markdownPath, markdown)]);
    return inventory;
  }

  await Promise.all([writeFile(jsonPath, json), writeFile(markdownPath, markdown)]);
  return inventory;
}

const isDirectExecution =
  process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (isDirectExecution) {
  const argumentsList = process.argv.slice(2);
  const unknownArgument = argumentsList.find((argument) => argument !== "--check");

  if (unknownArgument) {
    console.error(`Unknown argument: ${unknownArgument}`);
    process.exitCode = 1;
  } else {
    generateComponentInventory({ check: argumentsList.includes("--check") }).catch((error) => {
      console.error(error instanceof Error ? error.message : String(error));
      process.exitCode = 1;
    });
  }
}
